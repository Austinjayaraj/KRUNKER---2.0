def get_level_config(level_number: int) -> Dict[str, Any]:
    if level_number not in CAMPAIGN_LEVELS:
        raise ValueError(f"Invalid campaign level number: {level_number}")
    return dict(CAMPAIGN_LEVELS[level_number])


def get_all_level_configs() -> List[Dict[str, Any]]:
    return [dict(CAMPAIGN_LEVELS[k]) for k in sorted(CAMPAIGN_LEVELS.keys())]
